int LowPassIndex(int low_pass)
{
    // The track gives (argument - 64) / 64, the channel adds 1, and the voice clamps the sum to 0..1. So an argument of
    // 0 or less gives the lowest cutoff.
    const int index = std::max(low_pass, 0);
    return index <= kLastLowPass ? index : -1;
}

int LowPassHz(int index)
{
    return kLowPassHz[std::clamp(index, 0, kLastLowPass)];
}

uint8_t SfzLowPassValue(int low_pass)
{
    return static_cast<uint8_t>(std::clamp(0x40 - low_pass, 0, 127));
}

uint8_t SfzBiquadValue(int biquad_type, int biquad_value)
{
    return biquad_type >= 1 && biquad_type <= 5 ? static_cast<uint8_t>(std::clamp(biquad_value, 0, 127)) : 0;
}

int BiquadStep(int biquad_type, int biquad_value)
{
    // The track stores the argument / 127. Zero, or a type with no preset, disables the filter. The presets'
    // coefficient functions (Wii Music, 0x800b3b7c onwards) take the row at the value times the last row's index,
    // rounded towards zero. The band-passes scale value * (2 - value) instead. The game doesn't clamp the value to 1. A
    // band-pass argument above 127 then picks a lower row there. CC104 holds only 0 to 127, and revosf2 clamps the
    // argument to that range.
    const float value = std::clamp(static_cast<float>(biquad_value) / 127.0f, 0.0f, 1.0f);
    if (value <= 0.0f || biquad_type < 1 || biquad_type > 5)
    {
        return -1;
    }

    const auto row = [](float x, int last)
    {
        return std::clamp(static_cast<int>(static_cast<float>(last) * x), 0, last);
    };
    switch (biquad_type)
    {
    case 1:
        return row(value, 111);
    case 2:
        return row(value, 96);
    case 3:
        return row(value * (2.0f - value), 121);
    default:
        return row(value * (2.0f - value), 92);
    }
}

SoundFontFilter ToSoundFont(int low_pass, int biquad_type, int biquad_value)
{
    SoundFontFilter sf;
    const int index = LowPassIndex(low_pass);
    if (index >= 0)
    {
        sf.cutoff = kLowPassCutoff[index];
    }

    // Two active low-passes use the lower cutoff.
    const int step = BiquadStep(biquad_type, biquad_value);
    if (biquad_type == 1 && step >= 0 && kBiquadLowPass[step].cutoff < sf.cutoff)
    {
        sf = kBiquadLowPass[step];
    }

    return sf;
}

uint8_t FilterControllerValue(uint16_t cutoff)
{
    const int steps = (kFilterOpen - static_cast<int>(cutoff)) * 128;
    return static_cast<uint8_t>(std::clamp((steps + kFilterControllerRange / 2) / kFilterControllerRange, 0, 127));
}

int SfzLowPassCutoff(int index)
{
    return kSfzLowPassCutoff[std::clamp(index, 0, kLastLowPass)];
}

SfzBiquad SfzBiquadStep(int type, int step)
{
    const auto at = [step](const auto& table)
    {
        const int last = static_cast<int>(std::size(table)) - 1;
        return table[std::clamp(step, 0, last)];
    };
    switch (type)
    {
    case 1:
        return at(kSfzBiquad1);
    case 2:
        return at(kSfzBiquad2);
    case 3:
        return at(kSfzBiquad3);
    case 4:
        return at(kSfzBiquad4);
    default:
        return at(kSfzBiquad5);
    }
}

